/**
 * Packages the module system itself needs in a host application.
 *
 * The SDK is here because the generated wiring imports `@trustsystem/module-sdk/nest`,
 * and the registry because a module reads its own declarations from the catalog.
 * They are added explicitly rather than relied on as transitive dependencies: npm
 * links a `file:` dependency but does not install that package's own unpublished
 * `@trustsystem/*` requirements, so a transitive-only assumption leaves the application
 * unable to resolve the import — which is a `tsc` error at build time and a boot
 * failure at run time.
 */
const MODULE_SYSTEM_PACKAGES = [
  { name: '@trustsystem/module-sdk', directory: 'packages/module-sdk' },
  { name: '@trustsystem/module-registry', directory: 'packages/module-registry' },
];

/** Dependency specifiers for the module packages being installed. */
export function moduleDependencies(
  entries: ModuleCatalogEntry[],
  frameworkPath: string,
): Record<string, string> {
  const additions: Record<string, string> = {};
  const root = resolve(frameworkPath);

  // `file:` while the packages are unpublished, exactly as generation does for the
  // framework packages.
  for (const { name, directory } of MODULE_SYSTEM_PACKAGES) {
    additions[name] = `file:${join(root, directory)}`;
  }

  for (const entry of entries) {
    additions[entry.packaging.packageName] = `file:${join(root, entry.packaging.directory)}`;
  }

  return additions;
}

/**
 * Reads a module's `install/` tree.
 *
 * Every destination path is contained with `resolveWithin`, on every file — a
 * payload path is the one input here that could escape the application directory.
 */
async function collectPayload(
  frameworkPath: string,
  entry: ModuleCatalogEntry,
  applicationRoot: string,
): Promise<PlannedFile[]> {
  const payloadRoot = join(resolve(frameworkPath), entry.packaging.directory, 'install');

  // A module with no payload is legitimate: search owns no tables and adds no
  // application files.
  if (!existsSync(payloadRoot)) return [];

  const files: PlannedFile[] = [];

  for (const relative of await listFilesRecursively(payloadRoot)) {
    const target = toPosixPath(relative);
    const contents = await readFile(join(payloadRoot, relative), 'utf8');

    files.push(
      await plannedFile(applicationRoot, target, contents, {
        source: entry.metadata.id,
        // A schema fragment is owned by the module: reinstalling must be able to
        // refresh it, and it is not a file anybody should be editing by hand.
        managed: true,
      }),
    );
  }

  return files;
}

async function plannedFile(
  applicationRoot: string,
  path: string,
  contents: string,
  options: { managed?: boolean; source: string },
): Promise<PlannedFile> {
  const absolutePath = resolveWithin(applicationRoot, path);

  return {
    path,
    absolutePath,
    contents: normalizeLineEndings(contents),
    rendered: true,
    exists: existsSync(absolutePath),
    source: options.source,
    ...(options.managed ? { managed: true } : {}),
  };
}

/** A file that must already exist and is transformed rather than replaced. */
async function mergedFile(
  applicationRoot: string,
  path: string,
  transform: (current: string) => string,
): Promise<PlannedFile> {
  const absolutePath = resolveWithin(applicationRoot, path);

  if (!existsSync(absolutePath)) {
    throw new GeneratorError(
      'invalid_input',
      `${path} is missing from ${applicationRoot}.`,
      'This does not look like a complete generated application.',
    );
  }

  return {
    path,
    absolutePath,
    contents: normalizeLineEndings(transform(await readFile(absolutePath, 'utf8'))),
    rendered: true,
    exists: true,
    source: 'installer',
    managed: true,
  };
}

/**
 * Refuses to overwrite anything the installer does not own.
 *
 * The check is on the *content* of the file on disk, not on its path: a path could
 * match by accident, while the marker is only there if a previous install put it
 * there. A file that exists, is not a merge target, and has no marker, is somebody's
 * code — and the run stops rather than replacing it.
 */
/** `model Foo {` and `enum Foo {` at the start of a line. */
const PRISMA_DECLARATION = /^\s*(?:model|enum)\s+(\w+)\s*\{/gm;

function declaredPrismaTypes(contents: string): string[] {
  return [...contents.matchAll(PRISMA_DECLARATION)].map((match) => match[1] as string);
}

/**
 * Refuses an install whose Prisma fragment redefines a model the application already has.
 *
 * Prisma merges every file in `prisma/schema/` into one schema, so two files declaring
 * `model WorkflowDefinition` is not an override — it is a schema that will not compile.
 * Without this check the installer writes the fragment happily and the application only
 * breaks later, at `prisma generate`, with an error naming a file the developer did not
 * write. Templates that build their own richer version of a module's domain are the
 * normal way to hit this, and the fix is a decision (use the template's, or the
 * module's) rather than something the installer can make on someone's behalf.
 */
async function assertNoPrismaModelCollisions(
  files: PlannedFile[],
  applicationRoot: string,
  installing: ModuleCatalogEntry[],
): Promise<void> {
  const planned = files.filter(
    (file) => file.path.startsWith('prisma/schema/') && file.path.endsWith('.prisma'),
  );
  if (planned.length === 0) return;

  const schemaDirectory = resolveWithin(applicationRoot, 'prisma/schema');
  if (!existsSync(schemaDirectory)) return;

  // A fragment the installer is itself writing is not competing with itself.
  const plannedPaths = new Set(planned.map((file) => file.path));
  const owners = new Map<string, string>();

  for (const name of await readdir(schemaDirectory)) {
    if (!name.endsWith('.prisma')) continue;

    const relative = `prisma/schema/${name}`;
    if (plannedPaths.has(relative)) continue;

    const contents = await readFile(join(schemaDirectory, name), 'utf8');
    for (const type of declaredPrismaTypes(contents)) owners.set(type, relative);
  }

  const collisions: { type: string; fragment: string; existing: string }[] = [];

  for (const file of planned) {
    for (const type of declaredPrismaTypes(file.contents)) {
      const existing = owners.get(type);
      if (existing) collisions.push({ type, fragment: file.path, existing });
    }
  }

  if (collisions.length === 0) return;

  const detail = collisions
    .map((clash) => `  ${clash.type}: ${clash.fragment} would redefine ${clash.existing}`)
    .join('\n');

  throw new GeneratorError(
    'invalid_input',
    `Installing ${installing.map((entry) => entry.metadata.id).join(', ')} would define ${collisions.length === 1 ? 'a model that' : 'models that'} the application already defines:\n${detail}`,
    'This application already implements that domain. Either keep its own schema and do not install the module, or remove the existing fragment first.',
  );
}

function assertNoUnownedOverwrites(
  files: PlannedFile[],
  applicationRoot: string,
  loaded: LoadedManifest,
): void {
  const problems: string[] = [];

  for (const file of files) {
    if (!file.exists) continue;
    if (MERGED_FILES.has(file.path)) continue;

    const current = readFileSyncSafe(file.absolutePath);
    if (current !== null && isManagedContent(current)) continue;

    problems.push(file.path);
  }

  if (problems.length === 0) return;

  throw new GeneratorError(
    'target_not_empty',
    `Refusing to overwrite ${problems.length} file(s) the installer does not own: ${problems.join(', ')}.`,
    `Move or delete them, or install into a clean checkout. ${
      loaded.manifest.modules.length > 0
        ? 'A previous install would have left the marker comment in place; its absence means the file was edited.'
        : 'These files predate any module installation.'
    }`,
  );
}

function readFileSyncSafe(path: string): string | null {
  try {
    return readFileSync(path, 'utf8');
  } catch {
    return null;
  }
}

/** Locates the framework checkout from the module packages' directory. */
export function resolveFrameworkPath(startDirectory: string = __dirname): string {
  let current = resolve(startDirectory);

  for (let depth = 0; depth < 10; depth += 1) {
    if (existsSync(join(current, 'packages', 'modules'))) return current;

    const parent = dirname(current);
    if (parent === current) break;
    current = parent;
  }

  throw new GeneratorError(
    'template_not_found',
    'Could not locate the framework checkout.',
    'Run the CLI from a TrustOS framework checkout, or pass --framework-path.',
  );
}
