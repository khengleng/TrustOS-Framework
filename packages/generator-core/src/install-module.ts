/**
 * Local module installation.
 *
 * The whole operation is plan-then-apply, like generation, and for the same
 * reason: `--dry-run` has to run the identical code path and stop before the
 * write, or it is not telling the truth.
 *
 * What makes installing into an *existing* project different from generating a new
 * one is that most of the target directory belongs to somebody else. Three rules
 * follow, and together they are the answer to "never overwrite custom code":
 *
 *   1. A file the installer does not own, that already exists, is a conflict. The
 *      run stops and names it.
 *   2. The files it does own carry a marker and are regenerated from the full
 *      installed set, so uninstalling later leaves nothing stale behind.
 *   3. `package.json`, `trustos.json` and `.env.example` are parsed and merged,
 *      never rewritten wholesale.
 *
 * The composition root — `app.module.ts`, with the guard order that is the
 * security model — is never touched.
 */

export interface InstallModuleRequest {
  /** Module ids to install. Dependencies are added automatically. */
  moduleIds: string[];
  /** Application root, containing `trustos.json`. */
  applicationRoot: string;
  /**
   * Framework checkout, used to find each module's `install/` payload and to
   * rewrite `@trustsystem/*` dependencies to `file:` links.
   */
  frameworkPath: string;
  /** Overrides the version recorded in the application manifest. */
  frameworkVersion?: string;
  /** Install optional dependencies too. Off by default. */
  includeOptional?: boolean;
  /** Explicit timestamp, so the same inputs produce identical output. */
  generatedAt?: string;
  /** Allow a module marked `deprecated`. */
  allowDeprecated?: boolean;
}

export interface InstallModulePlan {
  plan: GenerationPlan;
  applicationRoot: string;
  /** Modules that will be installed, dependency-first. */
  order: ModuleCatalogEntry[];
  /** Pulled in because something requested depends on them. */
  addedForDependencies: string[];
  /** Requested but already present. */
  alreadyInstalled: string[];
  /** Optional dependencies that were not installed. */
  skippedOptional: string[];
  /** Schema fragments written; each needs a migration. */
  migrations: string[];
  /** True when the application had no module-config file before this run. */
  createdModuleConfig: boolean;
  /**
   * True when `app.module.ts` already spreads `TRUSTOS_MODULE_IMPORTS`.
   *
   * Applications generated by this framework version do; one generated earlier
   * needs the line added by hand, and the installer says so rather than telling
   * everybody to check.
   */
  appModuleWired: boolean;
}

export interface InstallModuleResult extends ApplyResult {
  applicationRoot: string;
  installed: string[];
  alreadyInstalled: string[];
  addedForDependencies: string[];
  migrations: string[];
  nextSteps: string[];
}

const MODULES_DIRECTORY = 'apps/api/src/modules';
const INSTALLED_MODULES_FILE = `${MODULES_DIRECTORY}/trustos-modules.ts`;
const MODULE_CONFIG_FILE = `${MODULES_DIRECTORY}/module-config.ts`;
const MODULES_DOC_FILE = 'docs/modules.md';
const ENV_EXAMPLE_FILE = '.env.example';
const PACKAGE_JSON_FILE = 'package.json';

/** Files the installer is allowed to merge into rather than treat as conflicts. */
const MERGED_FILES = new Set([PACKAGE_JSON_FILE, ENV_EXAMPLE_FILE, 'trustos.json']);

/**
 * Builds the installation plan.
 *
 * Everything that can fail — an unknown module, an incompatible framework, a
 * conflicting file, a missing payload — fails here, before anything is written.
 */
export async function planModuleInstall(request: InstallModuleRequest): Promise<InstallModulePlan> {
  const applicationRoot = resolve(request.applicationRoot);
  const loaded = await loadApplicationManifest(applicationRoot);
  const frameworkVersion = request.frameworkVersion ?? loaded.manifest.frameworkVersion;

  if (!loaded.manifest.generated.api) {
    throw new GeneratorError(
      'invalid_input',
      'This application was generated without an API, so there is nowhere to mount a module.',
      'Modules expose HTTP routes and need apps/api.',
    );
  }

  const already = installedModuleIds(loaded.manifest);

  let resolved;
  try {
    resolved = resolveInstallOrder(MODULE_CATALOG, request.moduleIds, {
      frameworkVersion,
      installed: already,
      ...(request.includeOptional === undefined
        ? {}
        : { includeOptional: request.includeOptional }),
    });
  } catch (error) {
    // The registry's failures are the installer's failures, translated so the CLI
    // has one error type to report.
    if (isModuleRegistryError(error)) {
      throw new GeneratorError('invalid_input', error.message, error.hint);
    }
    throw error;
  }

  if (!request.allowDeprecated) {
    const deprecated = resolved.order.filter((entry) => entry.metadata.stability === 'deprecated');
    if (deprecated.length > 0) {
      throw new GeneratorError(
        'invalid_input',
        `Deprecated module(s): ${deprecated.map((entry) => entry.metadata.id).join(', ')}.`,
        'Pass --force to install one anyway.',
      );
    }
  }

  const generatedAt = request.generatedAt ?? new Date().toISOString();

  // The full set after this run: what was there plus what is being added. Managed
  // files are regenerated from this, never appended to.
  const installedAfter: InstalledModule[] = [
    ...loaded.manifest.modules,
    ...resolved.order.map((entry) => ({
      id: entry.metadata.id,
      version: entry.metadata.version,
      installedAt: generatedAt,
      installedAsDependency: resolved.addedForDependencies.includes(entry.metadata.id),
    })),
  ];

  const allEntries = installedAfter.map((module) => requireModule(module.id));

  const files: PlannedFile[] = [];
  const migrations: string[] = [];

  // --- each module's own payload -------------------------------------------
  for (const entry of resolved.order) {
    for (const file of await collectPayload(request.frameworkPath, entry, applicationRoot)) {
      files.push(file);
      if (file.path.startsWith('prisma/schema/')) migrations.push(file.path);
    }
  }

  // --- managed wiring -------------------------------------------------------
  files.push(
    await plannedFile(
      applicationRoot,
      INSTALLED_MODULES_FILE,
      renderInstalledModulesFile(allEntries),
      {
        managed: true,
        source: 'installer',
      },
    ),
  );

  // --- created once ---------------------------------------------------------
  const moduleConfigPath = resolveWithin(applicationRoot, MODULE_CONFIG_FILE);
  const createdModuleConfig = !existsSync(moduleConfigPath);

  if (createdModuleConfig) {
    files.push(
      await plannedFile(applicationRoot, MODULE_CONFIG_FILE, renderModuleConfigFile(allEntries), {
        source: 'installer',
      }),
    );
  }

  // --- managed documentation ------------------------------------------------
  files.push(
    await plannedFile(
      applicationRoot,
      MODULES_DOC_FILE,
      renderModulesDoc(allEntries, {
        applicationName: loaded.manifest.application.displayName,
        frameworkVersion,
      }),
      { managed: true, source: 'installer' },
    ),
  );

  // --- merged files ---------------------------------------------------------
  files.push(
    await mergedFile(applicationRoot, PACKAGE_JSON_FILE, (current) =>
      mergePackageJson(current, moduleDependencies(resolved.order, request.frameworkPath)),
    ),
  );

  files.push(
    await mergedFile(applicationRoot, ENV_EXAMPLE_FILE, (current) =>
      mergeEnvExample(current, resolved.order),
    ),
  );

  files.push(
    await plannedFile(
      applicationRoot,
      'trustos.json',
      mergeApplicationManifest(loaded, installedAfter),
      { managed: true, source: 'installer' },
    ),
  );

  assertNoUnownedOverwrites(files, applicationRoot, loaded);
  await assertNoPrismaModelCollisions(files, applicationRoot, resolved.order);

  return {
    plan: {
      projectRoot: applicationRoot,
      files: files.sort((left, right) => (left.path < right.path ? -1 : 1)),
      overrides: [],
    },
    applicationRoot,
    order: resolved.order,
    addedForDependencies: resolved.addedForDependencies,
    alreadyInstalled: resolved.alreadyInstalled,
    skippedOptional: resolved.skippedOptional,
    migrations,
    createdModuleConfig,
    appModuleWired: appModuleSpreadsImports(applicationRoot),
  };
}

/**
 * Whether the composition root already spreads the installed-module list.
 *
 * A text check rather than a parse, and that is the right level: the installer
 * never edits this file, so all it needs to know is whether to print an
 * instruction.
 */
function appModuleSpreadsImports(applicationRoot: string): boolean {
  const path = join(applicationRoot, 'apps', 'api', 'src', 'app.module.ts');
  const contents = readFileSyncSafe(path);
  return contents !== null && contents.includes('TRUSTOS_MODULE_IMPORTS');
}

/** Plans and applies. */
export async function installModules(
  request: InstallModuleRequest,
  options: ApplyOptions = {},
): Promise<InstallModuleResult> {
  const planned = await planModuleInstall(request);

  // `force: true` here means "managed files may be rewritten", which `applyPlan`
  // already permits on its own; the flag covers the merged files, whose conflict
  // check happened in `assertNoUnownedOverwrites` with far more context than the
  // writer has.
  const result = await applyPlan(planned.plan, { ...options, force: true });

  return {
    ...result,
    applicationRoot: planned.applicationRoot,
    installed: planned.order.map((entry) => entry.metadata.id),
    alreadyInstalled: planned.alreadyInstalled,
    addedForDependencies: planned.addedForDependencies,
    migrations: planned.migrations,
    nextSteps: nextStepsFor(planned),
  };
}

/** What a developer does after a successful install, in order. */
export function nextStepsFor(planned: InstallModulePlan): string[] {
  const steps: string[] = ['npm install'];

  if (planned.migrations.length > 0) {
    steps.push('npm run db:migrate    # applies the module schema fragments');
  }

  if (!planned.appModuleWired) {
    steps.push('Add ...TRUSTOS_MODULE_IMPORTS to the imports array in apps/api/src/app.module.ts');
  }

  steps.push('Seed TRUSTOS_MODULE_PERMISSIONS onto roles in prisma/seed.ts', 'npm test');

  if (planned.createdModuleConfig) {
    steps.push('Optional: set module configuration in apps/api/src/modules/module-config.ts');
  }

  return steps;
}

