#!/usr/bin/env node
/**
 * Generates `docs/industry-reference.md` from the template specs.
 *
 * The same argument as the registry: a reference page maintained by hand beside a generated tree
 * describes the templates as they were when somebody last remembered to update it. Generated, it
 * describes them as they are.
 *
 * The prose that is *not* derivable — why a template models something the way it does, what it
 * deliberately excludes — lives in the spec file as `description`, `migrationNotes` and
 * `outOfScope`, and comes through here. This script writes no opinions of its own.
 */

import { writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { TEMPLATE_SPECS } from './template-specs.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const target = join(root, 'docs/industry-reference.md');

const CATEGORY_TITLES = {
  commerce: 'Commerce',
  'financial-services': 'Financial services',
  'business-operations': 'Business operations',
  education: 'Education',
  health: 'Health',
  'public-sector': 'Public and social',
  messaging: 'Messaging mini apps',
  portal: 'Portals',
};

/** Templates that exist by hand and belong in the reference beside the generated ones. */
const HAND_WRITTEN = [
  {
    id: 'merchant',
    displayName: 'TrustOS Merchant',
    category: 'commerce',
    description:
      'Merchant structure: merchants, stores, branches and merchant members, with an admin ' +
      'console over all four. The parent of the e-commerce and marketplace templates.',
    entities: [
      { name: 'Merchant', description: 'A merchant business. One organization may operate several.' },
      { name: 'Store', description: 'A storefront belonging to a merchant.' },
      { name: 'Branch', description: 'A physical location of a store.' },
      { name: 'MerchantMember', description: 'A person acting on behalf of a merchant.' },
    ],
    outOfScope: ['payments', 'loyalty', 'campaigns', 'inventory', 'settlement'],
    migrationNotes: 'Structure only. Payments, loyalty, campaigns, inventory and settlement are deliberately absent.',
  },
  {
    id: 'payment-gateway',
    displayName: 'TrustOS Payment Gateway',
    category: 'financial-services',
    description:
      'A merchant-facing payment API: API keys, webhook configuration, a transaction dashboard ' +
      'and a settlement dashboard, over a provider interface with no provider behind it.',
    entities: [],
    outOfScope: ['payment provider integrations', 'card networks', 'PCI scope', 'chargeback handling'],
    migrationNotes:
      'Amounts are integer minor units, documented as such on the column. No provider is ' +
      'integrated and none should be: the seam is the provider interface.',
  },
  {
    id: 'learning',
    displayName: 'TrustOS Learning',
    category: 'education',
    description:
      'A light learning record: student profiles, learning sessions and quiz attempts. For the ' +
      'full platform — courses, lessons, assignments, certificates — use `education`.',
    entities: [],
    outOfScope: ['AI quiz generation', 'payments', 'school management', 'teacher marketplace'],
    migrationNotes: 'Records learning activity only.',
  },
  {
    id: 'telegram-mini-app',
    displayName: 'TrustOS Telegram Mini App (deprecated)',
    category: 'messaging',
    description:
      'Deprecated in favour of `telegram-miniapp`, which shares one mini app shell with the ' +
      'WhatsApp and Messenger templates. It still generates, so an application built on it can ' +
      'keep upgrading.',
    entities: [],
    outOfScope: ['Telegram Bot API calls', 'payment providers'],
    migrationNotes: 'Use `telegram-miniapp` for new projects.',
  },
];

const all = [...TEMPLATE_SPECS, ...HAND_WRITTEN];

const byId = new Map(TEMPLATE_SPECS.map((spec) => [spec.id, spec]));

/**
 * The full inheritance chain, hand-written ancestors included.
 *
 * `byId` only knows the generated specs, so a chain that reaches `merchant` would stop one short
 * — and a marketplace that did not mention merchants would send somebody looking for a template
 * that already exists.
 */
const handWrittenById = new Map(HAND_WRITTEN.map((spec) => [spec.id, spec]));

const chainOf = (spec) => {
  const chain = [];
  let current = spec;

  while (current) {
    chain.unshift(current.id);
    current = current.extends
      ? (byId.get(current.extends) ?? handWrittenById.get(current.extends))
      : undefined;
  }

  return chain;
};

const lines = [];

lines.push('# Industry reference');
lines.push('');
lines.push(
  'Every industry template, what it models, and what it deliberately does not. Generated by ' +
    '`scripts/sync-industry-reference.mjs` from `scripts/template-specs.mjs` — the same file that ' +
    'generates the template trees, so this page cannot describe a template that no longer exists.',
);
lines.push('');
lines.push('For the architecture behind all of them, see [templates.md](templates.md). For writing');
lines.push('a new one, see [template-development-guide.md](template-development-guide.md).');
lines.push('');
lines.push('## How to read an entry');
lines.push('');
lines.push('**Extends** means the template is layered on another: a generated project contains both');
lines.push("layers' models, screens and permissions. A clinic is not a smaller hospital — a hospital");
lines.push('is a clinic plus wards, and the inheritance runs that way round.');
lines.push('');
lines.push('**Out of scope** is a commitment, not a backlog. A template that grew a payment provider');
lines.push('would stop being reusable by the deployment that has a different one.');
lines.push('');
lines.push('## Contents');
lines.push('');

for (const [category, title] of Object.entries(CATEGORY_TITLES)) {
  const members = all.filter((spec) => spec.category === category);
  if (members.length === 0) continue;

  lines.push(`- **${title}** — ${members.map((spec) => `\`${spec.id}\``).join(', ')}`);
}

lines.push('');

for (const [category, title] of Object.entries(CATEGORY_TITLES)) {
  const members = all.filter((spec) => spec.category === category);
  if (members.length === 0) continue;

  lines.push(`## ${title}`);
  lines.push('');

  for (const spec of members) {
    lines.push(`### \`${spec.id}\` — ${spec.displayName}`);
    lines.push('');
    lines.push(spec.description);
    lines.push('');

    if (spec.extends) {
      lines.push(`**Extends** \`${chainOf(spec).join('` → `')}\``);
      lines.push('');
    }

    lines.push('```');
    lines.push(`trustos new ${spec.id} --name my-app`);
    lines.push('```');
    lines.push('');

    if (spec.entities.length > 0) {
      lines.push('| Entity | What it holds |');
      lines.push('| --- | --- |');

      for (const entity of spec.entities) {
        const summary = String(entity.description)
          .replace(/\s+/g, ' ')
          .replace(/\|/g, '\\|')
          .replace(/`/g, '`');
        lines.push(`| \`${entity.name}\` | ${summary} |`);
      }

      lines.push('');
    }

    lines.push(`**Out of scope.** ${spec.outOfScope.join(', ')}.`);
    lines.push('');
    lines.push(`**Notes.** ${String(spec.migrationNotes).replace(/^Initial release\.\s*/, '')}`);
    lines.push('');
  }
}

lines.push('## Choosing between neighbours');
lines.push('');
lines.push('Several templates model adjacent things. The distinctions that matter:');
lines.push('');
lines.push('| If you need | Use | Not |');
lines.push('| --- | --- | --- |');
lines.push('| A shop with its own stock and prices | `ecommerce` | `marketplace`, which adds sellers you do not have |');
lines.push('| Third parties selling through you | `marketplace` | `ecommerce`, which has no commission model |');
lines.push('| Stored value and transfers | `wallet` | `digital-bank`, which adds account numbers and statements |');
lines.push('| Customer-facing accounts and statements | `digital-bank` | `wallet`, which has no customer record |');
lines.push('| Courses and certificates | `education` | `learning`, which only records activity |');
lines.push('| Terms, classes and attendance | `school` | `education`, which has no calendar |');
lines.push('| Outpatient only | `clinic` | `hospital`, which adds wards you will not fill |');
lines.push('| Inpatient stays | `hospital` | `clinic`, which has no beds |');
lines.push('| A back office over the framework | `admin-portal` | `staff-portal`, which is about a person’s own work |');
lines.push('| Somebody’s tasks and approvals | `staff-portal` | `admin-portal`, which is about the system |');
lines.push('');
lines.push('None of these is a one-way door: every template generates a plain TypeScript project');
lines.push('with no runtime dependency on the template it came from. What you cannot do cheaply is');
lines.push('*re-generate* over a project you have started editing, which is why the choice is worth');
lines.push('five minutes.');
lines.push('');

await writeFile(target, `${lines.join('\n')}`, 'utf8');

process.stdout.write(`Wrote ${all.length} entries to ${target}.\n`);
